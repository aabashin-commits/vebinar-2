// bitrix.js — подключение CRM-формы Битрикс24 к кнопкам лендинга.
//
// ⚠️ ФОРМА ПОКА НЕ ПОДКЛЮЧЕНА. Клиент заводит под вебинар отдельную CRM-форму
// (чтобы лиды с вебинара не смешивались с обычными заявками школы) и передаёт
// её ID. Что сделать, когда ID придёт, — в разделе «Форма Битрикс24» файла
// CLAUDE.md этой папки: два фрагмента в index.html, ничего больше.
//
// Как это работает. Лоадер Битрикса ищет на странице элементы с атрибутом
// data-b24-form и вешает на них открытие формы. Мы держим для этого скрытую
// кнопку .b24-trigger, а openForm() имитирует клик по ней — так все CTA
// страницы идут через один общий хелпер (см. main.js), и разметке кнопок
// про Битрикс знать не нужно.
//
// Файл грузится ПОСЛЕ main.js, поэтому его openForm перекрывает дефолтный.
// Но только если форма реально подключена: пока в разметке нет скрипта-лоадера,
// мы ничего не переопределяем, и работает fallback из main.js — плавный скролл
// к секции регистрации с телефоном школы. Мёртвых кнопок на странице нет
// ни до подключения формы, ни после.
(() => {
  'use strict';

  const trigger = document.querySelector('.b24-trigger');
  if (!trigger) return;

  // Лоадер Битрикса объявляется в index.html как <script data-b24-form="click/NNN/xxxxxx">.
  // Нет его — форма не подключена, оставляем поведение из main.js.
  const loader = document.querySelector('script[data-b24-form]');
  if (!loader) return;

  // Тема заявки (data-open-form="…") в CRM-форму не передаётся: у click-формы
  // Битрикса нет нашего скрытого поля. Понадобится предзаполнение — делается
  // на стороне Битрикса через событие b24:form:init.
  window.openForm = () => trigger.click();
})();
